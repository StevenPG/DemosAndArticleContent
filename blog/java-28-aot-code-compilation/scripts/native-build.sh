#!/usr/bin/env bash
# Builds the GraalVM native image baselines (spring-rest and cli-tool).
# warmup-cpu has no native variant: its whole point is watching a JIT warm up.
source "$(dirname "$0")/lib.sh"
mkdir -p "$WORK/native"
cd "$ROOT"

echo "==> spring-rest: Spring AOT processing + native-image ($(basename "$GRAALVM_HOME"))"
JAVA_HOME="$GRAALVM_HOME" GRAALVM_HOME="$GRAALVM_HOME" ./gradlew --no-daemon -q :apps:spring-rest:nativeCompile
cp apps/spring-rest/build/native/nativeCompile/spring-rest "$WORK/native/spring-rest"

echo "==> cli-tool: native-image (reflection config generated by picocli-codegen)"
"$GRAALVM_HOME/bin/native-image" --no-fallback -jar "$CLI_JAR" -o "$WORK/native/flightlog" >/dev/null

ls -lh "$WORK/native"
